// Extracts a seed slice from the SnuhiLearn lesson bank (Prasad's own product).
// DATA ONLY — no SnuhiLearn code is reused. Output: src/seed-data.js
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = process.env.SEED_SRC || join(process.env.HOME, 'workspace/ai-tutor/backend/data/lessons');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'seed-data.js');

const SUBJECTS = {
  cb3491: 'Cryptography', '18cs51': 'Management & Entrepreneurship', '18cs52': 'Computer Networks',
  '18cs53': 'Database Management Systems', '18cs54': 'Automata & Compiler Design',
  '18cs55': 'Python Programming', '18cs56': 'Unix Programming',
};
const titleize = (slug) => slug.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());

const lessons = [];
for (const file of readdirSync(SRC).filter((f) => f.endsWith('.json') && !f.startsWith('stage2'))) {
  const bank = JSON.parse(readFileSync(join(SRC, file), 'utf8'));
  const code = Object.keys(SUBJECTS).find((k) => file.toLowerCase().includes(k)) || 'general';
  for (const [id, L] of Object.entries(bank.lessons || {})) {
    lessons.push({
      id,
      subject: SUBJECTS[code] || 'General',
      title: titleize(id.split('-').slice(1).join('-') || id),
      intro: L.intro || '',
      keyFacts: (L.key_facts || []).slice(0, 8),
      commonMistakes: (L.common_mistakes || []).slice(0, 3),
      sections: (L.sections || []).slice(0, 3).map((s) => ({ heading: s.heading || '', body: (s.body || '').slice(0, 900) })),
      workedExamples: (L.worked_examples || []).slice(0, 2).map((w) => ({
        problem: w.problem || '', steps: (w.steps || []).slice(0, 8), answer: w.answer || '',
      })),
      practice: (L.practice || []).slice(0, 4).map((p) => ({ question: p.question || '', solution: p.solution || '' })),
    });
  }
}
lessons.sort((a, b) => a.subject.localeCompare(b.subject) || a.title.localeCompare(b.title));
const banner = `// AUTO-GENERATED by tools/extract-seed.mjs — seed DATA slice from the SnuhiLearn
// lesson bank (482 lessons; this slice ships ${lessons.length}). Content only; all app code is new.
`;
writeFileSync(out, banner + 'export const SEED_LESSONS = ' + JSON.stringify(lessons, null, 1) + ';\n');
console.log(`Wrote ${lessons.length} lessons -> ${out}`);
